function outFile = export_gc_prediction_channel(matFile, splitName, sampleIndex, targetOffset, outFile, phySampleRate)
%EXPORT_GC_PREDICTION_CHANNEL Export gc_vis_gen_data CSI tensors to C++ channel text.
%
% outFile = export_gc_prediction_channel(matFile, splitName, sampleIndex,
%     targetOffset, outFile, phySampleRate)
%
% The input .mat is produced by gc_vis_gen_data.m and contains X/Y tensors:
%   X_<split>: [samples, 96, 4P] noisy CSI history
%   Y_<split>: [samples, 24, 4P] future clean/predicted CSI
%
% The C++ reader expects:
%   P
%   h_real h_imag doppler_hz delay_samples
%   ...
%
% targetOffset is 1-based inside the target window. Use 1 for the first
% predicted PHY frame after the observation window.

arguments
    matFile (1, :) char
    splitName (1, :) char {mustBeMember(splitName, {'train', 'val', 'test'})} = 'test'
    sampleIndex (1, 1) double {mustBeInteger, mustBePositive} = 1
    targetOffset (1, 1) double {mustBeInteger, mustBePositive} = 1
    outFile (1, :) char = ''
    phySampleRate (1, 1) double {mustBePositive} = 25e6
end

S = load(matFile, sprintf('Y_%s', splitName), 'cfg', 'profileName');
yName = sprintf('Y_%s', splitName);
if ~isfield(S, yName)
    error('Missing variable %s in %s.', yName, matFile);
end
Y = S.(yName);
if ndims(Y) ~= 3 || size(Y, 3) < 4 || mod(size(Y, 3), 4) ~= 0
    error('%s must have shape [samples, targetWindow, 4P].', yName);
end
if sampleIndex > size(Y, 1)
    error('sampleIndex exceeds %s sample count.', yName);
end
if targetOffset > size(Y, 2)
    error('targetOffset exceeds %s target window.', yName);
end
if ~isfield(S, 'cfg') || ~isfield(S.cfg, 'DelayRes') || ~isfield(S.cfg, 'DopplerResHz')
    error('cfg.DelayRes and cfg.DopplerResHz are required.');
end

feature = squeeze(Y(sampleIndex, targetOffset, :)).';
numPaths = size(Y, 3) / 4;

if isempty(outFile)
    [folder, base, ~] = fileparts(matFile);
    outFile = fullfile(folder, sprintf('%s_%s_sample%06d_t%02d.channel.txt', ...
        base, splitName, sampleIndex, targetOffset));
end

fid = fopen(outFile, 'w');
if fid < 0
    error('Failed to open output file: %s', outFile);
end
cleanup = onCleanup(@() fclose(fid));

fprintf(fid, '# Generated by export_gc_prediction_channel.m\n');
if isfield(S, 'profileName')
    fprintf(fid, '# profileName = %s\n', string(S.profileName));
end
fprintf(fid, '# source = %s\n', matFile);
fprintf(fid, '# split = %s sampleIndex = %d targetOffset = %d\n', splitName, sampleIndex, targetOffset);
fprintf(fid, '# format: P followed by h_real h_imag doppler_hz delay_samples\n');
fprintf(fid, '%d\n', numPaths);

for p = 1:numPaths
    base = 4 * (p - 1);
    hReal = feature(base + 1);
    hImag = feature(base + 2);
    delayBin = feature(base + 3);
    dopplerBin = feature(base + 4);
    dopplerHz = dopplerBin * S.cfg.DopplerResHz;
    delaySamples = delayBin * S.cfg.DelayRes * phySampleRate;
    fprintf(fid, '%.9g %.9g %.9g %.9g\n', hReal, hImag, dopplerHz, delaySamples);
end
end
